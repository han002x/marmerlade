import { readFile, writeFile } from 'node:fs/promises';
import { z } from 'zod';
import { changeSchema, diagramSchema } from '../../../src/workspaceSchema.ts';
import { previewRequestSchema, gifRequestSchema } from '../../../src/renderContract.ts';

const schemas = [
  {
    filename: 'workspace.schema.json',
    id: 'urn:marmerlade:workspace:v3',
    schema: z.object({ version: z.literal(3), diagram: diagramSchema }),
  },
  {
    filename: 'changes.schema.json',
    id: 'urn:marmerlade:apply-changes',
    schema: z.object({ revision: z.number().int().nonnegative(), changes: z.array(changeSchema).min(1) }),
  },
  { filename: 'preview.schema.json', id: 'urn:marmerlade:render-preview', schema: previewRequestSchema },
  { filename: 'gif.schema.json', id: 'urn:marmerlade:export-gif', schema: gifRequestSchema },
];

for (const { filename, id, schema } of schemas) {
  const content = JSON.stringify({
    ...z.toJSONSchema(schema, { target: 'draft-2020-12', io: 'input' }),
    $id: id,
    $comment: 'Generated by export-schemas.mjs from runtime Zod schemas. Graph integrity and Markdown semantics require separate validation.',
  }, null, 2) + '\n';
  const file = new URL(`../references/${filename}`, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== content) {
      throw new Error(`${filename} is stale. Run export-schemas.mjs without --check.`);
    }
    console.log(`Current: ${filename}`);
  } else {
    await writeFile(file, content);
    console.log(`Wrote: ${filename}`);
  }
}
